  let language = 'vi';
  const listeners = new Set();
  const normalize = value => value === 'en' ? 'en' : 'vi';
  const format = (value, vars = {}) => String(value).replace(/\{(\w+)\}/g, (_, key) => vars[key] ?? '');
  function t(key, vars = {}) {
    return format(STRINGS[language]?.[key] ?? STRINGS.vi[key] ?? key, vars);
  }
  function setCurrent(value, notify = true) {
    const next = normalize(value);
    const changed = next !== language;
    language = next;
    if (typeof document !== 'undefined') document.documentElement.lang = language;
    if (changed && notify) for (const listener of listeners) listener(language);
    return language;
  }
  async function load() {
    try {
      const data = await chrome.storage.local.get('quickpasteLanguage');
      return setCurrent(data.quickpasteLanguage, false);
    } catch (_) { return setCurrent('vi', false); }
  }
  async function setLanguage(value) {
    const next = setCurrent(value);
    try { await chrome.storage.local.set({ quickpasteLanguage: next }); } catch (_) {}
    return next;
  }
  function translateDocument(root = document) {
    root.documentElement.lang = language;
    for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
    for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
    for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
    for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
    for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  }
  function onChange(listener) { listeners.add(listener); return () => listeners.delete(listener); }

  if (globalThis.chrome?.storage?.onChanged) {
    chrome.storage.onChanged.addListener((changes, area) => {
      if (area === 'local' && changes.quickpasteLanguage) setCurrent(changes.quickpasteLanguage.newValue);
    });
  }
  globalThis.QuickPasteI18n = { t, load, setLanguage, setCurrent, translateDocument, onChange, get language() { return language; } };
